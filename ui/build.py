#!/usr/bin/env python3
"""Stamp the TouchOSC layout with its OSC contract and write the manifest SuperCollider checks it against.

    ui/build.py              stamp ui/main.tosc, regenerate ui/main.xml and ui/ui_manifest.scd
    ui/build.py --from-xml   same, but take ui/main.xml as the source (after editing the XML by hand)
    ui/build.py --check      change nothing; exit 1 if any of the three files is out of date (pre-commit hook)

The contract is every OSC message of every control: address, control type, button type, send / receive flags
and the arguments with their conversions and ranges. Its hash (8 hex digits) is the UI version. Moving controls
or changing colours keeps the hash, changing an address or a range changes it.

Stamping writes a Lua script into the layout's root node. It holds the hash, sends /ui/hello <hash> <build> to
SuperCollider when the layout loads and whenever SC sends /ui/ping, and shows SC's verdict (/ui/status) in the
label "uiStatus" (on top of the heartbeat button; added once, move it in the editor as you like).

Only the standard library is used; the XML is edited as text so TouchOSC's own format (CDATA etc.) is kept.
"""

import argparse
import datetime
import hashlib
import re
import sys
import uuid
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path

UI_DIR = Path(__file__).resolve().parent
TOSC = UI_DIR / "main.tosc"
XML = UI_DIR / "main.xml"
MANIFEST = UI_DIR / "ui_manifest.scd"

STATUS_LABEL = "uiStatus"
# frame of the status label when it is first added: on top of the heartbeat button in the right column
STATUS_FRAME = (1670, 600, 250, 100)

LUA_TEMPLATE = """-- Generated by ui/build.py: the layout's version. Do not edit here, run ui/build.py instead.
local UI_HASH  = '{hash}'
local UI_BUILD = '{build}'

local helloAt = 0

local function hello()
  sendOSC('/ui/hello', UI_HASH, UI_BUILD)
end

local function statusLabel()
  return self:findByName('{label}', true)
end

function init()
  local status = statusLabel()
  if status then
    status.values.text = 'UI ' .. UI_HASH .. ' ?'
  end
  hello()
  helloAt = getMillis() + 2000  -- once more when the network is surely up
end

function update()
  if helloAt > 0 and getMillis() > helloAt then
    helloAt = 0
    hello()
  end
end

function onReceiveOSC(message, connections)
  local path = message[1]
  if path == '/ui/ping' then
    hello()
  elseif path == '/ui/status' then
    local args = message[2]
    local status = statusLabel()
    if status and args[1] then
      status.values.text = tostring(args[1].value)
      if args[2] and args[2].value ~= 0 then
        status.textColor = Color(0.55, 1, 0.55, 1)
      else
        status.textColor = Color(1, 0.25, 0.25, 1)
      end
    end
  end
end
"""


# ---------------------------------------------------------------- reading the layout

def read_tosc(path):
    return zlib.decompress(path.read_bytes()).decode("utf-8")


def collapse(xml_text):
    """Pretty-printed XML (main.xml) -> TouchOSC's single-line form. Whitespace between tags only."""
    parts = re.split(r"(<!\[CDATA\[.*?\]\]>)", xml_text, flags=re.S)
    return "".join(p if p.startswith("<![CDATA[") else re.sub(r">\s+<", "><", p.strip()) for p in parts)


def pretty(xml_text):
    """One tag per line like the existing main.xml; CDATA stays on the line of its element."""
    parts = re.split(r"(<!\[CDATA\[.*?\]\]>)", xml_text, flags=re.S)
    return "".join(p if p.startswith("<![CDATA[") else p.replace("><", ">\n<") for p in parts) + "\n"


def props(node):
    ps = node.find("properties")
    return {} if ps is None else {p.findtext("key"): p for p in ps}


def contract(xml_text):
    """Sorted contract lines, one per OSC message, and the address lists the manifest needs."""
    root = ET.fromstring(xml_text).find("node")
    lines, sends, receives = [], set(), set()

    def walk(node, names):
        pr = props(node)
        name = pr["name"].findtext("value") if "name" in pr else ""
        chain = [name] + names
        button_type = pr["buttonType"].findtext("value") if "buttonType" in pr else "-"
        messages = node.find("messages")
        for osc in ([] if messages is None else messages.findall("osc")):
            path = ""
            for part in osc.find("path").findall("partial"):
                kind, value = part.findtext("type"), part.findtext("value")
                if kind == "CONSTANT":
                    path += value
                elif kind == "PROPERTY" and re.fullmatch(r"(parent\.)*name", value):
                    path += chain[value.count("parent.")]
                else:
                    path += "{%s:%s}" % (kind, value)
            args = ",".join(
                "%s:%s:%s:%s:%s" % tuple(a.findtext(k) for k in ("type", "conversion", "value", "scaleMin", "scaleMax"))
                for a in osc.find("arguments").findall("partial"))
            send, receive = osc.findtext("send") == "1", osc.findtext("receive") == "1"
            if osc.findtext("enabled") != "1":
                continue
            lines.append("%s %s button=%s send=%d receive=%d args=%s"
                         % (path, node.get("type"), button_type, send, receive, args))
            if send and node.get("type") != "LABEL":  # a label's text only changes from outside
                sends.add(path)
            if receive:
                receives.add(path)
        children = node.find("children")
        for child in ([] if children is None else children.findall("node")):
            walk(child, chain)

    walk(root, [])
    lines.sort()
    digest = hashlib.sha256("\n".join(lines).encode("utf-8")).hexdigest()[:8]
    return digest, lines, sorted(sends), sorted(receives)


def stamped_hash(xml_text):
    m = re.search(r"local UI_HASH\s*=\s*'([0-9a-f]+)'", root_properties(xml_text)[1])
    return m.group(1) if m else None


# ---------------------------------------------------------------- stamping (text edits)

def root_properties(xml_text):
    """(start, block, end) of the root node's <properties> block: the first one in the document."""
    start = xml_text.index("<properties>")
    end = xml_text.index("</properties>", start) + len("</properties>")
    return start, xml_text[start:end], end


def cdata(text):
    return "<![CDATA[%s]]>" % text


def set_root_script(xml_text, lua):
    start, block, end = root_properties(xml_text)
    prop = "<property type='s'><key>%s</key><value>%s</value></property>" % (cdata("script"), cdata(lua))
    existing = re.search(r"<property type='s'><key><!\[CDATA\[script\]\]></key>.*?</property>", block, flags=re.S)
    if existing:
        block = block[:existing.start()] + prop + block[existing.end():]
    else:
        # TouchOSC keeps properties sorted by key: insert before the first key that sorts after "script"
        pos = None
        for m in re.finditer(r"<property type='\w'><key><!\[CDATA\[(\w+)\]\]></key>", block):
            if m.group(1) > "script":
                pos = m.start()
                break
        pos = pos if pos is not None else block.rindex("</properties>")
        block = block[:pos] + prop + block[pos:]
    return xml_text[:start] + block + xml_text[end:]


def set_prop(node_text, key, value_xml):
    pattern = r"(<property type='\w'><key><!\[CDATA\[%s\]\]></key><value>).*?(</value></property>)" % key
    new, n = re.subn(pattern, lambda m: m.group(1) + value_xml + m.group(2), node_text, count=1, flags=re.S)
    if n != 1:
        raise SystemExit("build.py: label template has no property '%s'" % key)
    return new


def ensure_status_label(xml_text):
    """Add the status label to the root node's children unless a control of that name exists."""
    if "<value>%s</value>" % cdata(STATUS_LABEL) in xml_text:
        return xml_text
    # template: a label without OSC messages (all of them carry the same property set)
    template = None
    for m in re.finditer(r"<node ID='[^']*' type='LABEL'>.*?</node>", xml_text, flags=re.S):
        if "<messages>" not in m.group(0) or "<messages></messages>" in m.group(0):
            template = m.group(0)
            break
    if template is None:
        raise SystemExit("build.py: no label without OSC messages found to copy the status label from")
    x, y, w, h = STATUS_FRAME
    label = re.sub(r"ID='[^']*'", "ID='%s'" % uuid.uuid1(), template, count=1)
    label = set_prop(label, "name", cdata(STATUS_LABEL))
    label = set_prop(label, "frame", "<x>%d</x><y>%d</y><w>%d</w><h>%d</h>" % (x, y, w, h))
    label = set_prop(label, "textSize", "14")
    label = set_prop(label, "interactive", "0")
    label = re.sub(r"(<key><!\[CDATA\[text\]\]></key>.*?<default>).*?(</default>)",
                   lambda m: m.group(1) + cdata("UI ?") + m.group(2), label, count=1, flags=re.S)
    # the root node's <children> block closes last: "</children></node></lexml>"
    pos = xml_text.rindex("</children>")
    return xml_text[:pos] + label + xml_text[pos:]


# ---------------------------------------------------------------- manifest

def manifest_values(path):
    if not path.exists():
        return None, None
    text = path.read_text(encoding="utf-8")
    h = re.search(r'hash:\s*"([0-9a-f]+)"', text)
    b = re.search(r'build:\s*"([^"]*)"', text)
    return (h.group(1) if h else None), (b.group(1) if b else None)


def sc_list(paths):
    return "[\n" + "".join('\t\t"%s",\n' % p for p in paths) + "\t]"


def render_manifest(digest, build, sends, receives, lines):
    return """// ============================================================
// UI manifest — GENERATED by ui/build.py from ui/main.tosc, do not edit
// ============================================================
// The OSC contract of the TouchOSC layout this code expects. osc/ui_version.scd compares the hash with the
// one the tablet reports (/ui/hello) and checks the addresses against the registered OSCdefs.
//
// Contract (hash = first 8 hex digits of the sha256 of these lines):
%s
// ============================================================

~uiContract = (
	hash: "%s",
	build: "%s",
	// addresses the tablet sends (each needs an OSCdef)
	sends: %s,
	// addresses the tablet listens to
	receives: %s
);
""" % ("".join("//   %s\n" % l for l in lines), digest, build, sc_list(sends), sc_list(receives))


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--from-xml", action="store_true", help="use ui/main.xml as the source instead of ui/main.tosc")
    ap.add_argument("--check", action="store_true", help="only check that everything is up to date")
    opts = ap.parse_args()

    source = collapse(XML.read_text(encoding="utf-8")) if opts.from_xml else read_tosc(TOSC)
    digest, lines, sends, receives = contract(source)
    old_hash, old_build = manifest_values(MANIFEST)

    if opts.check:
        problems = []
        if stamped_hash(source) != digest:
            problems.append("ui/main.tosc carries version %s, its contract is %s" % (stamped_hash(source), digest))
        if old_hash != digest:
            problems.append("ui/ui_manifest.scd says %s, the layout's contract is %s" % (old_hash, digest))
        if XML.exists() and collapse(XML.read_text(encoding="utf-8")) != source:
            problems.append("ui/main.xml differs from ui/main.tosc")
        if problems:
            print("UI out of date:\n  " + "\n  ".join(problems) + "\nRun: python3 ui/build.py", file=sys.stderr)
            return 1
        print("UI %s up to date (%d OSC messages)." % (digest, len(lines)))
        return 0

    # the build date only moves when the contract changes, so a cosmetic edit leaves the manifest alone
    build = old_build if (old_hash == digest and old_build) else datetime.date.today().isoformat()

    xml_text = ensure_status_label(source)
    xml_text = set_root_script(xml_text, LUA_TEMPLATE.format(hash=digest, build=build, label=STATUS_LABEL))
    ET.fromstring(xml_text)  # still well-formed?
    if contract(xml_text)[0] != digest:
        raise SystemExit("build.py: stamping changed the contract (bug)")

    TOSC.write_bytes(zlib.compress(xml_text.encode("utf-8"), 9))
    XML.write_text(pretty(xml_text), encoding="utf-8")
    MANIFEST.write_text(render_manifest(digest, build, sends, receives, lines), encoding="utf-8")
    change = "unchanged" if old_hash == digest else "was %s" % old_hash
    print("UI %s (%s), %d OSC messages, build %s." % (digest, change, len(lines), build))
    print("Wrote ui/main.tosc, ui/main.xml, ui/ui_manifest.scd.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
